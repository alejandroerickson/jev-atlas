def shared_kind(key, area):
    """Which shared component a fragment entry duplicates, or None to keep it."""
    t, tr, rl, page = key.get("text"), key.get("text_regex", ""), key.get("row_label"), key.get("page")
    if tr == "^Sort by ":
        return "sort"
    if tr == "^(First|Previous|Next|Last)$" or (t in ("First", "Previous", "Next", "Last") and key.get("role") == "button"):
        return "pager"
    if t == "Dismiss":
        return "dismiss"
    if t == "Close dialog":
        return "close"
    if (t == "Cancel" or tr == "^Cancel$") and page in DIALOG_OVERLAYS:
        return "cancel"
    if rl == "Add a comment" or tr.startswith("^(Open )?Add a comment"):
        return "comment"
    if t == "Post comment":
        return "post"
    if t == "Values behind this chart":
        return "values"
    if re.match(r"\^(\(read from\|computed by\)|read from|computed by)", tr):
        return "provenance"
    if t == "User Manual" and key.get("role") == "link":
        return "manual-link"
    return None


# Chrome and account-menu/tray labels no catch-all record link may capture.
CHROME_LABELS = ["ADIT home", "Skip to content", "Portfolio", "Projects", "Programmes", "Drilling", "Assays",
                 "Resources", "Optimiser", "Admin", "Approvals", "User Manual", "Open", "My profile",
                 "Preferences", "Notification settings", "All notifications", "Mark all read"]
GUARD = "(?!(?:" + "|".join(re.escape(x) for x in CHROME_LABELS) + ")$)(?!Approvals\\s*\\()(?!User Manual)(?!Open\\s)"
guarded = 0


def guard_catch_all(key):
    """Prefix a catch-all record-link regex with the chrome guard."""
    global guarded
    tr = key.get("text_regex")
    if key.get("role") == "link" and tr and tr.startswith("^(?!") and key.get("page"):
        key["text_regex"] = "^" + GUARD + tr[1:]
        guarded += 1


dialog_first, chrome, areas_rest, removed = [], [], [], {}
for area in AREAS:
    for c in parts[area]["controls"]:
        c = copy.deepcopy(c)
        kind = shared_kind(c["key"], area)
        if kind:
            removed.setdefault(kind, []).append(area)
            continue
        guard_catch_all(c["key"])
        c["area"] = area
        if area == "portfolio-global":
            chrome.append(c)
        elif c["key"].get("page") in DIALOG_OVERLAYS:
            dialog_first.append(c)
        else:
            areas_rest.append(c)

# A button in a form row borrows the row's label, so a field keyed {page, row_label}
# alone also took the dialog's Save and Cancel (observed live): key those fields by role too.
ROLE_FIX = {("optimiser-dlg-save-scenario", "Name"): "textbox",
            ("reject-batch-dialog", "Reason sent to the laboratory"): "textbox"}
for c in dialog_first + areas_rest:
    k = c["key"]
    if set(k) == {"page", "row_label"} and (k["page"], k["row_label"]) in ROLE_FIX:
        k["role"] = ROLE_FIX[(k["page"], k["row_label"])]

shared = []
for kind, entry in SHARED.items():
    e = copy.deepcopy(entry)
    e["area"] = "shared"
    shared.append(e)

