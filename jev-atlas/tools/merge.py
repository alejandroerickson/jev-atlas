seen_keys = {}
for c in controls:
    for f in c["key"]:
        assert f in A.KEY_FIELDS, f
    if "page" in c["key"]:
        assert c["key"]["page"] in pages, c["key"]
    for f in ("text_regex", "id_regex", "href_regex"):
        if f in c["key"]:
            re.compile(c["key"][f])
    sig = json.dumps(c["key"], sort_keys=True)
    if sig in seen_keys:
        sys.exit(f"duplicate key {sig} ({seen_keys[sig]} and {c['area']})")
