"""Merge the seven ADIT atlas fragments into one atlas: jev-atlas/atlas/adit.json.

    python3 jev-atlas/tools/merge.py    # writes atlas/adit.json, loads it with the harness's atlas.py,
                                        # prints a summary and the file's sha256

The fragments in atlas/parts/ are generated by tools/<area>/build.py (gen.py for
programmes); regenerate a fragment there, then rerun this script. Nothing here is
hand-edited JSON: every change the merge makes to a fragment is a rule below.

What the merge does (see atlas/README.md):
- one atlas-level `selectors`;
- the URL pages in an explicit order (specific routes before general ones; the
  not-found page last, as a catch-all), overlays after them;
- the five chrome facts (signed-in user, people and roles, highlighted section, unread and awaiting
  counts, toast) once, as the atlas-level `global_facts_js`, and the fragments' own
  copies of the signed-in and toast facts dropped;
- cross-area `leads_to` values rewritten as page ids;
- one copy of each shared component (sort headings, pager, toast Dismiss and Open,
  dialog close cross and Cancel, comments box and Post comment, chart disclosure,
  provenance stamp, footer and account-menu User Manual links, and a fallback for
  breadcrumbs);
- top bar, breadcrumb, footer and account menu told apart by `landmark`;
- the second-round rules in harness2.py (catch-all record links replaced by route
  keys, entries broken by the new row labels rekeyed, row buttons keyed by their row,
  virtual controls the reader now offers natively replaced by entries);
- control order: dialog-overlay entries first (they share text with the page
  buttons that open them), then the global chrome fragment in its own order (the
  account left column before the account menu and tray), then the areas, then the
  shared components.
"""
