def duplicate_fact(expr):
    """A fragment's own copy of a chrome fact: the signed-in user or the toast message."""
    if expr in CHROME_FACTS:
        return True
    if "toast" in expr and "dialog" not in expr:
        return True
    if "Signed in as" in expr and "currentUserId" in expr:
        return True
    return False


